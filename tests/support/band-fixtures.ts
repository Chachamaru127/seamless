import { statusResult, type StructureItem } from '../../src/status.ts';
import type { RequestRecord } from '../../src/request-store.ts';
const at = '2026-10-04T09:00:00Z';
function request(stage: string, status = 'observed', id = 'req1', delivery = stage === 'unknown' ? 'unknown' : stage === 'pending' ? 'pending' : stage === 'rejected' ? 'rejected' : 'submitted') {
  const record: RequestRecord = { id, at: Date.parse(at), status: delivery, hash: 'fixture',
    sender: { id: 'claude:self', provider: 'claude', nativeId: 'self', generation: 'g1', cwd: '/work' },
    recipient: { id: 'codex:12345678-abc', provider: 'codex', nativeId: '12345678-abc', generation: 'g1', cwd: '/work/project' } }
  const destination: StructureItem[] = [], source: StructureItem[] = []
  if (status === 'observed') {
    if (stage === 'reached' || stage === 'processing') destination.push({ id: 'peer', type: 'peer', at, turnId: 'turn', position: 0, peer: { id, sender: record.sender } })
    if (stage === 'processing') destination.push({ id: 'answer', type: 'assistant', at, turnId: 'turn', position: 1 })
    if (stage === 'replied') source.push({ id: 'reply', type: 'peer', at, peer: { id: 'response', replyTo: id, sender: record.recipient } })
  }
  return statusResult(record, destination, source, Date.parse(at))
}
